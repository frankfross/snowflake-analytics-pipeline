-- 01_setup.sql — one-time setup: warehouse, database, schema, CSV file format.
-- Cost-aware defaults: XSMALL, auto-suspend after 60 idle seconds.

CREATE WAREHOUSE IF NOT EXISTS PORTFOLIO_WH
  WITH WAREHOUSE_SIZE = 'XSMALL'
       AUTO_SUSPEND = 60
       AUTO_RESUME = TRUE
       INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS PORTFOLIO_DB;
CREATE SCHEMA IF NOT EXISTS PORTFOLIO_DB.ANALYTICS;

CREATE FILE FORMAT IF NOT EXISTS PORTFOLIO_DB.ANALYTICS.CSV_FF
  TYPE = 'CSV'
  FIELD_DELIMITER = ','
  SKIP_HEADER = 1
  NULL_IF = ('NULL', 'null', '');
